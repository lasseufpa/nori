/**
 * @file nori-print-attributes.cc
 * @brief Print the attributes and trace sources of the NORI classes as reStructuredText.
 *
 * The output is the "Attributes and trace sources" chapter of the NORI manual:
 *
 *   ./ns3 run nori-print-attributes > contrib/nori/doc/source/attributes.rst
 *
 * Only the attributes and trace sources declared by each class are listed; inherited
 * ones are documented by the parent class (ns-3 or nr).
 */

#include "ns3/E2-interface.h"
#include "ns3/E2-report.h"
#include "ns3/E2-term-helper.h"
#include "ns3/core-module.h"
#include "ns3/nr-gnb-rrc.h"
#include "ns3/nr-rl-mac-scheduler-ofdma.h"
#include "ns3/oran-interface.h"

#include <iostream>
#include <string>
#include <vector>

using namespace ns3;

namespace
{

/// Indent every line after the first so that multi-line text fits in a list-table cell
std::string
Cell(std::string text)
{
    if (text.empty())
    {
        return "\\-";
    }
    std::string out;
    for (char c : text)
    {
        out += c;
        if (c == '\n')
        {
            out += "       ";
        }
    }
    return out;
}

void
PrintTitle(const std::string& title, char underline)
{
    std::cout << title << "\n" << std::string(title.size(), underline) << "\n\n";
}

void
PrintTypeId(TypeId tid)
{
    PrintTitle("``" + tid.GetName() + "``", '-');
    std::cout << "Parent: ``" << tid.GetParent().GetName() << "``\n\n";

    if (tid.GetAttributeN() == 0)
    {
        std::cout << "No attributes declared by this class.\n\n";
    }
    else
    {
        std::cout << ".. list-table:: Attributes\n"
                  << "   :header-rows: 1\n"
                  << "   :widths: 22 46 16 16\n\n"
                  << "   * - Name\n     - Description\n     - Type\n     - Initial value\n";
        for (uint32_t i = 0; i < tid.GetAttributeN(); ++i)
        {
            const TypeId::AttributeInformation info = tid.GetAttribute(i);
            std::string value;
            if (info.initialValue && info.checker)
            {
                value = info.initialValue->SerializeToString(info.checker);
            }
            const std::string type = info.checker ? info.checker->GetValueTypeName() : "";
            std::cout << "   * - ``" << info.name << "``\n"
                      << "     - " << Cell(info.help) << "\n"
                      << "     - " << Cell(type.empty() ? "" : "``" + type + "``") << "\n"
                      << "     - " << Cell(value.empty() ? "" : "``" + value + "``") << "\n";
        }
        std::cout << "\n";
    }

    if (tid.GetTraceSourceN() > 0)
    {
        std::cout << ".. list-table:: Trace sources\n"
                  << "   :header-rows: 1\n"
                  << "   :widths: 30 50 20\n\n"
                  << "   * - Name\n     - Description\n     - Callback\n";
        for (uint32_t i = 0; i < tid.GetTraceSourceN(); ++i)
        {
            const TypeId::TraceSourceInformation info = tid.GetTraceSource(i);
            std::cout << "   * - ``" << info.name << "``\n"
                      << "     - " << Cell(info.help) << "\n"
                      << "     - ``" << info.callback << "``\n";
        }
        std::cout << "\n";
    }
}

} // namespace

int
main(int argc, char* argv[])
{
    CommandLine cmd(__FILE__);
    cmd.Parse(argc, argv);

    const std::vector<TypeId> types = {
        E2TermHelper::GetTypeId(),
        E2Interface::GetTypeId(),
        E2Termination::GetTypeId(),
        NoriE2Report::GetTypeId(),
        NrRLMacSchedulerOfdma::GetTypeId(),
    };

    PrintTitle("Attributes and trace sources", '=');
    std::cout << ".. This file is generated by examples/nori-print-attributes.cc. Do not edit.\n\n"
              << "Attributes and trace sources declared by the NORI classes. Set them with\n"
              << "``Config::SetDefault(\"ns3::<Class>::<Attribute>\", ...)``, with\n"
              << "``SetAttribute`` on the object, or from the command line with\n"
              << "``--ns3::<Class>::<Attribute>=<value>``.\n\n";

    for (const auto& tid : types)
    {
        PrintTypeId(tid);
    }
    return 0;
}
